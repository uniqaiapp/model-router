#!/usr/bin/env node
// Render data/prices.json as Markdown. With --write, overwrites references/price-table.md.
// README and SKILL.md link to that file instead of repeating numbers, so there is one source of truth.
//
//   node scripts/table.mjs            # print to stdout
//   node scripts/table.mjs --write    # write references/price-table.md
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { loadPrices, ROOT, TIERS, fmtPrice, fmtInt, parseArgs } from "./lib/prices.mjs";

export function renderMarkdown(data) {
  const L = [];
  L.push("# Price table");
  L.push("");
  L.push(`Generated by \`node scripts/table.mjs --write\` from [\`data/prices.json\`](../data/prices.json). Do not edit by hand.`);
  L.push("");
  L.push(`USD per 1M tokens, standard (non-batch) tier, short context. Table updated **${data.updated}**. \`—\` means the vendor page lists no such price. Rows whose tier differs from the price band carry a note.`);
  L.push("");
  L.push("Tier bands (by output price): " + TIERS.map((t) => {
    const b = data.tier_bands[t];
    return `**${t}** ${b.max_output == null ? "above the smart band" : "≤ $" + b.max_output}`;
  }).join(" · "));
  L.push("");
  for (const t of TIERS) {
    L.push(`## ${t[0].toUpperCase() + t.slice(1)} tier`);
    L.push("");
    L.push("| Model | Provider | Input | Cached input | Output | Context | Checked | Notes |");
    L.push("|---|---|---:|---:|---:|---:|---|---|");
    for (const m of data.models.filter((x) => x.tier === t)) {
      const notes = [];
      if (m.tier_note) notes.push(m.tier_note);
      if (m.long_context) notes.push(`≥ ${fmtInt(m.long_context.threshold)} prompt tokens: ${fmtPrice(m.long_context.input)} / ${fmtPrice(m.long_context.cached_input)} / ${fmtPrice(m.long_context.output)}`);
      if (m.promo) notes.push(`price through ${m.promo.until}; from ${m.promo.after.from}: ${fmtPrice(m.promo.after.input)} / ${fmtPrice(m.promo.after.cached_input)} / ${fmtPrice(m.promo.after.output)}`);
      if (m.notes) notes.push(m.notes);
      L.push(`| \`${m.id}\` | ${data.providers[m.provider].name} | ${fmtPrice(m.input)} | ${fmtPrice(m.cached_input)} | ${fmtPrice(m.output)} | ${m.context == null ? "—" : fmtInt(m.context)} | [${m.checked}](${m.source}) | ${notes.join(". ") || ""} |`);
    }
    L.push("");
  }
  L.push("## Providers");
  L.push("");
  L.push("| Provider | Pricing page | Batch discount | Checked |");
  L.push("|---|---|---|---|");
  for (const [id, p] of Object.entries(data.providers)) {
    L.push(`| ${p.name} (\`${id}\`) | <${p.pricing_url}> | ${p.batch_discount == null ? "not verified" : "×" + p.batch_discount} | ${p.checked} |`);
  }
  L.push("");
  L.push("To refresh: open each pricing page, edit `data/prices.json`, set `checked`, run `node scripts/check.mjs`, then `node scripts/table.mjs --write` and `node scripts/regen-examples.mjs`.");
  L.push("");
  return L.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const a = parseArgs(process.argv.slice(2));
  if (a.help || a.h) {
    console.log("usage: node scripts/table.mjs [--write] [--prices PATH]");
    process.exit(0);
  }
  const data = loadPrices(a.prices ? String(a.prices) : undefined);
  const md = renderMarkdown(data);
  if (a.write) {
    const out = path.join(ROOT, "references", "price-table.md");
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, md);
    console.log(`wrote ${path.relative(ROOT, out)} (${data.models.length} models)`);
  } else process.stdout.write(md);
}
